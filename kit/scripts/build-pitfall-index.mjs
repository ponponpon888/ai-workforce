#!/usr/bin/env node
/**
 * build-pitfall-index.mjs — Generate data/pitfalls.index.json from the record files.
 *
 * The index is a build product that is committed. CI regenerates it and fails on a diff, so
 * it cannot quietly fall behind the records. That means the output has to be deterministic:
 * records are sorted by id and nothing here reads the clock. A timestamp in this file would
 * turn every CI run red.
 *
 * It carries one thing the records deliberately do not: stale_risk. A permissions or hook
 * finding whose environment does not record which Claude Code version it was measured
 * against cannot be assumed to still hold, because the thing being measured is Claude Code.
 * That is a property of the record's age, not of how it was established, so it is derived
 * here rather than written by hand -- a hand-written freshness field is wrong the day after
 * it is written.
 *
 * `checks` is the part an external linter is meant to read: every detection that claims to be
 * machine-checkable, flattened with the id of the record it came from.
 *
 *   node kit/scripts/build-pitfall-index.mjs
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const schema = JSON.parse(readFileSync(join(repoRoot, 'data', 'pitfalls', '_schema.json'), 'utf8'));

const SETS = ['data/pitfalls', 'data/app-pitfalls'];
const OUT = join(repoRoot, 'data', 'pitfalls.index.json');

// --- read -------------------------------------------------------------------

const records = [];

for (const set of SETS) {
  const dir = join(repoRoot, set);
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir).sort()) {
    if (!name.endsWith('.json') || name.startsWith('_')) continue;
    records.push({ set: basename(set), file: `${set}/${name}`, record: JSON.parse(readFileSync(join(dir, name), 'utf8')) });
  }
}

records.sort((a, b) => (a.record.id < b.record.id ? -1 : a.record.id > b.record.id ? 1 : 0));

// --- derive -----------------------------------------------------------------

function staleRisk(record) {
  if (!record.environment) return 'not_applicable';
  if (!schema.stale_risk.layers.includes(record.layer)) return 'ok';
  return record.environment[schema.stale_risk.field] === schema.stale_risk.when_value ? 'unknown_version' : 'ok';
}

const tally = (values, keys) => {
  const out = {};
  for (const key of keys) {
    const n = values.filter((v) => v === key).length;
    if (n > 0) out[key] = n;
  }
  return out;
};

const entries = records.map(({ set, file, record }) => ({
  id: record.id,
  set,
  file,
  title: record.title,
  layer: record.layer,
  kind: record.kind,
  severity: record.severity,
  confidence: record.confidence,
  status: record.status ?? null,
  stale_risk: staleRisk(record),
  origin: record.origin,
  checkable: record.detection ? record.detection.checkable === true : false,
  related: record.related ?? [],
  tags: record.tags ?? [],
}));

const checks = records
  .filter(({ record }) => record.detection && record.detection.checkable === true)
  .map(({ record }) => ({
    id: record.id,
    kind: record.detection.kind,
    target: record.detection.target,
    pattern: record.detection.pattern,
    expect: record.detection.expect,
    message: record.detection.message ?? record.title,
    severity: record.severity,
  }));

const index = {
  $comment: [
    'Generated by kit/scripts/build-pitfall-index.mjs. Do not edit by hand.',
    'CI regenerates this file and fails if it differs from the committed copy.',
    'stale_risk is derived here and is not stored in any record.',
  ],
  schema_version: schema.schema_version,
  counts: {
    total: entries.length,
    by_set: tally(entries.map((e) => e.set), ['pitfalls', 'app-pitfalls']),
    by_confidence: tally(entries.map((e) => e.confidence), schema.enums.confidence),
    by_status: tally(entries.map((e) => e.status ?? 'none'), [...schema.enums.status, 'none']),
    by_kind: tally(entries.map((e) => e.kind), schema.enums.kind),
    by_layer: tally(entries.map((e) => e.layer), schema.enums.layer),
    by_stale_risk: tally(entries.map((e) => e.stale_risk), Object.keys(schema.stale_risk.values)),
    checkable: checks.length,
  },
  checks,
  records: entries,
};

writeFileSync(OUT, JSON.stringify(index, null, 2) + '\n', 'utf8');

console.log(`wrote ${OUT}`);
console.log(`  ${entries.length} record(s), ${checks.length} machine-checkable`);
for (const [risk, n] of Object.entries(index.counts.by_stale_risk)) {
  console.log(`  stale_risk ${risk}: ${n}`);
}
